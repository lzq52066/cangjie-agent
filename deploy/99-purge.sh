#!/usr/bin/env bash
# ============================================================
# 99 - 彻底卸载（⚠ 删除容器 + 所有数据卷：数据库/文件/日志全部清空）
# ============================================================
set -euo pipefail
cd "$(dirname "$0")"

read -p "[99] 将删除所有容器与数据卷（数据不可恢复），确认请输入 yes：" confirm
if [ "$confirm" != "yes" ]; then
  echo "[99] 已取消"
  exit 0
fi

docker compose down -v
echo "[99] 已卸载容器与数据卷"
